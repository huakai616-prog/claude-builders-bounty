def B(n):
    return next(b['t'] for b in TIMING['bars'] if b['bar'] == n)


def S(line, i):
    return TIMING['lines'][line]['syllables'][i]['start']


def EV(prefix):
    return next(e['t'] for e in TIMING['events'] if e['what'].startswith(prefix))


