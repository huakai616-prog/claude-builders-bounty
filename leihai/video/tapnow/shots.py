def gen_seconds(s):
    """建议在 TapNow 里生成的时长。短一点没关系，脚本会放慢到 85% 或停在最后一帧。"""
    d = s['t1'] - s['t0']
    return 5 if d <= 5.8 else 10


def check():
    """镜头必须从 0 连续排到音频结尾，不留空、不重叠。"""
    problems = []
    t = 0.0
    for s in SHOTS:
        if abs(s['t0'] - t) > 1e-6:
            problems.append(f"{s['id']} 从 {s['t0']:.3f} 开始，上一个镜头到 {t:.3f}")
        if s['t1'] <= s['t0']:
            problems.append(f"{s['id']} 的结束不晚于开始")
        t = s['t1']
    if abs(t - END) > 1e-6:
        problems.append(f'最后一个镜头到 {t:.3f}，音频到 {END:.3f}')
    ids = [s['id'] for s in SHOTS]
    for s in SHOTS:
        if s['reuse'] and s['reuse'].split('@')[0] not in ids:
            problems.append(f"{s['id']} 借用的 {s['reuse']} 不存在")
    return problems


# ---------------------------------------------------------------- 生成文档
def mmss(t):
    return f'{int(t // 60)}:{t % 60:05.2f}'


def write_markdown(path=HERE / '分镜与提示词.md'):
    must = [s for s in SHOTS if s['must']]
    videos = sum(1 for s in must if s['kind'] == 'video')
    L = []
    L.append('# 《泪海》×《等潮》TapNow 分镜与提示词\n')
    L.append('> 这份文件由 `shots.py` 生成，改镜头请改 `shots.py` 再运行 `python3 shots.py`。操作步骤见 `README.md`。\n')
    L.append(f'- 全片 {mmss(END)}，{len(SHOTS)} 个镜头：**必做 {len(must)} 个**（{videos} 段视频 + 1 张静帧），'
             f'可省 {len(SHOTS) - len(must)} 个（没做的话，脚本会自动借用别的镜头）。')
    L.append('- 时间是歌曲里的秒数，和你的 MP3 完全对齐。每个镜头生成 5 秒（标 10 秒的除外），多出来的脚本会剪掉。')
    L.append('- 每条提示词都已经带上了画风、角色和场景的固定描述，**整段复制**就行。改的时候只改「画面：」后面的部分。')
    L.append('- 图片模型不认中文的话（比如 Midjourney），用文末的英文版画风和角色描述。\n')
    L.append('## 总览\n')
    L.append('| 镜头 | 时间 | 秒 | 音乐 | 画面 | |')
    L.append('|---|---|---|---|---|---|')
    for s in SHOTS:
        tag = '★必做' if s['must'] else '☆可省'
        if s['kind'] == 'reuse':
            tag = '借用'
        L.append(f"| {s['id']} | {mmss(s['t0'])} | {s['t1'] - s['t0']:.1f} | {s['music']} | {s['title']} | {tag} |")
    L.append('\n## 第一步：定妆（先做参考图）\n')
    L.append('这些图决定了阿旺和码头长什么样。满意之后，**每个镜头都把对应的参考图连到图片节点上**，前后才会一致。\n')
    for i, r in enumerate(REFS, 1):
        L.append(f"### R{i} {r['name']}（{r['how']}）\n")
        L.append('```text\n' + r['prompt'] + '\n```\n')
    L.append('## 第二步：逐个镜头生成\n')
    L.append('先用「首帧提示词」出图，挑一张满意的，再把这张图接到视频节点，用「视频提示词」生成视频。\n')
    L.append('负面提示词（有「不想要的内容」一栏就填上）：\n')
    L.append('```text\n' + NEG + '\n```\n')
    for s in SHOTS:
        d = s['t1'] - s['t0']
        tag = '★ 必做' if s['must'] else '☆ 可省'
        L.append(f"### {s['id']}　{tag}　{mmss(s['t0'])} → {mmss(s['t1'])}（{d:.2f} 秒）\n")
        L.append(f"- **音乐**：{s['music']}")
        L.append(f"- **画面**：{s['title']}")
        if s['kind'] == 'reuse':
            src, _, off = s['reuse'].partition('@')
            L.append(f'- **不用生成**：脚本默认借用 {src} 从第 {off or 0} 秒开始的画面。想单独做的话，按闪回的意思自己出一段，命名为 {s["id"]}。\n')
            continue
        L.append(f"- **参考图**：{s['refs']}")
        if s['kind'] == 'still':
            L.append('- **只要一张图**：这一镜是「时间静止」，不用生成视频，脚本会给图加一个很慢的推近。图片保存成 '
                     f"`{s['id']}.png`。")
        else:
            L.append(f'- **生成时长**：{gen_seconds(s)} 秒')
        if not s['must'] and s['reuse']:
            src, _, off = s['reuse'].partition('@')
            L.append(f'- **可省**：没做的话，脚本借用 {src} 的画面。')
        if s.get('note'):
            L.append(f"- **注意**：{s['note']}")
        if s['enter'] == 'dissolve':
            L.append(f"- **转场**：从上一个镜头叠化进来（{s['enter_len']} 秒），脚本自动做。")
        elif s['enter'] == 'flash':
            L.append(f"- **转场**：白光一闪进来（{s['enter_len']} 秒），脚本自动做。")
        L.append('')
        L.append('首帧提示词（图片）：\n')
        L.append('```text\n' + s['img'] + '\n```\n')
        if s['kind'] == 'video':
            L.append(f"视频提示词（图生视频，{gen_seconds(s)} 秒）：\n")
            L.append('```text\n' + s['vid'] + VID_TAIL + '\n```\n')
    L.append('## 附：英文版（给只认英文的模型）\n')
    L.append('画风：\n\n```text\n' + STYLE_EN + '\n```\n')
    L.append('阿旺：\n\n```text\n' + AWANG_EN + '\n```\n')
    L.append('负面提示词：\n\n```text\n' + NEG_EN + '\n```\n')
    path.write_text('\n'.join(L), encoding='utf-8')
    return path


